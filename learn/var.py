# 变量: 用一个名字, 存一段数据, 以后用名字就能拿出来
# 等号 = 不是"等于", 是"把右边放进左边的盒子"

name = "神"          # 盒子 name 里放了文字"小明"
clothes = "迷彩卫衣"    # 盒子 clothes 里放了"黑色皮衣"
price = 299            # 盒子 price 里放了数字 299

# 用 print 把盒子里的东西拿出来显示
print("店员:", name)
print("商品:", clothes)
print("价格:", price)

# 改一下盒子里的东西
price = 199
print("降价后价格:", price)
